"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path");
const root=path.join(__dirname,"..","smart-jkbms-bluetooth");
const nodes=JSON.parse(fs.readFileSync(path.join(root,"raw_temperature_flows.json"),"utf8"));
const fn=nodes.find(n=>n.id==="b120001300000001");
const debug=nodes.find(n=>n.id==="b120001300000002");
assert(fn&&debug&&debug.active===true);
const code=new Function("msg","context","node","Buffer","Date",fn.func);
const map=new Map(),context={get:k=>map.get(k),set:(k,v)=>map.set(k,v)};
let now=100000;const clock={now:()=>now},node={status:()=>{}};
const a="C8:47:80:1A:1A:EF",b="C8:47:80:1A:27:12";
function frame(addr,invalid=[]){
 const data=Buffer.alloc(300);
 data.set([0x55,0xAA,0xEB,0x90,0x02,0xA1],0);
 for(let i=0;i<16;i++)data.writeUInt16LE(3190+i,6+i*2);
 data.writeUInt32LE(0xFFFF,70);
 data.writeUInt32LE(51000,150);
 data[173]=21;
 data[214]=0x06;
 data.writeInt16LE(invalid.includes("T1")?32767:165,162);
 data.writeInt16LE(invalid.includes("T2")?32767:166,164);
 data.writeInt16LE(invalid.includes("MOS")?32767:185,144);
 data[299]=data.subarray(0,299).reduce((sum,x)=>(sum+x)&255,0);
 return {address:addr,type:2,crc_ok:true,raw_hex:data.toString("hex").toUpperCase()};
}
function run(payload){return code({payload},context,node,Buffer,clock);}
const r1=run(frame(a,["T1","MOS"]));
assert(Array.isArray(r1)&&Array.isArray(r1[0])&&r1[0].length===2);
assert(r1[0][0].payload.includes("T1=3276.7°C!"),r1[0][0].payload);
assert(r1[0][0].payload.includes("T2=16.6°C"),r1[0][0].payload);
assert(r1[0][0].payload.includes("MOS=3276.7°C!"),r1[0][0].payload);
assert(r1[0][1].payload.includes("invalides=T1,MOS (2/3)"),r1[0][1].payload);
assert(r1[0][1].payload.includes("absence-mask=0x06"));
const r2=run(frame(b,[]));
assert(r2&&r2[0].length===2);
assert(r2[0][1].payload.includes("invalides= (0/3)"),r2[0][1].payload);
for(const msg of [...r1[0],...r2[0]])assert(msg.payload.length<116,msg.payload);
assert.equal(run(frame(a,["T1","MOS"])),null);
now+=20001;
assert(run(frame(a,["T1","MOS"])),"per-BMS rate limiter");
assert.equal(run({...frame(a),crc_ok:false}),null);
assert.equal(run({address:a,type:2,crc_ok:true,raw_hex:"XYZ"}),null);
const assembler=JSON.parse(fs.readFileSync(path.join(root,"flows.json"),"utf8")).find(n=>n.id==="65ad8ac512b5e001");
assert(assembler&&assembler.wires[0].includes(fn.id),"Fresh installs must wire verified frames to the diagnostic");
console.log("Raw temperature diagnostics tests passed: per-BMS 20s, invalid probes, CRC guard, short output");