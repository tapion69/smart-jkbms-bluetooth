"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const root=path.join(__dirname,"..","smart-jkbms-bluetooth");
const nodes=JSON.parse(fs.readFileSync(path.join(root,"temperature_switch_flows.json"),"utf8"));
const fn=nodes.find(n=>n.id==="b121500000000001");
const dbg=nodes.find(n=>n.id==="b121500000000002");
assert(fn&&dbg&&dbg.active);
const exec=new Function("msg","context","node","Buffer","Date",fn.func);
const map=new Map(),context={get:k=>map.get(k),set:(k,v)=>map.set(k,v)};
let now=100000;
const clock={now:()=>now},status={status:()=>{}};
const a="C8:47:80:1A:1A:EF",b="C8:47:80:1A:27:12";
function frame(address,disabled){
 const buf=Buffer.alloc(300);
 buf.set([0x55,0xAA,0xEB,0x90,0x01,0x22],0);
 buf.writeUInt16LE(disabled?0x0002:0x0040,282);
 buf[299]=buf.subarray(0,299).reduce((s,v)=>(s+v)&255,0);
 return {address,type:1,crc_ok:true,raw_hex:buf.toString("hex").toUpperCase()};
}
const send=(p)=>exec({payload:p},context,status,Buffer,clock);
let first=send(frame(a,true));
assert(first&&first.payload.includes("Disable Temp. Sensor = ON"));
assert(first.payload.includes("surveillance températures DISABLED"));
assert(first.settings_snapshot.read_only===true);
assert(first.settings_snapshot.disable_temperature_sensors===true);
assert(first.settings_snapshot.raw_controls_hex==="0x0002");
assert.equal(send(frame(a,true)),null,"Rate limit repeats");
let second=send(frame(b,false));
assert(second&&second.payload.includes("Disable Temp. Sensor = OFF"));
assert(second.settings_snapshot.temperature_monitoring==="ENABLED");
assert.equal(send({...frame(a,true),type:2}),null,"Reject non-settings frames");
assert.equal(send({...frame(a,true),crc_ok:false}),null,"Reject invalid CRC");
const malformed=frame(a,true);malformed.raw_hex="00";assert.equal(send(malformed),null);
now+=1200;
const switchChanged=send(frame(a,false));
assert(switchChanged&&switchChanged.payload.includes("Disable Temp. Sensor = OFF"),"Changes must bypass throttle");
now+=60001;
assert(send(frame(a,false)),"periodic refresh after one minute");
const assembled=JSON.parse(fs.readFileSync(path.join(root,"flows.json"),"utf8")).find(n=>n.id==="65ad8ac512b5e001");
assert(assembled&&assembled.wires[0].includes(fn.id),"Fresh install must wire verified frames");
assert.equal(nodes.filter(n=>n.type==="mqtt out").length,0);
console.log("Switch read-only state OK: 2 batteries, both flags, CRC and frame guard, throttling, no writes/MQTT");