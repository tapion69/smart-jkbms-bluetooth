assert.equal(catchGoogle.payload.module,"jkbms");
assert.equal(catchGoogle.statusCode,undefined);
assert.equal(catchGoogle.responseUrl,undefined);
for(const field of ["country","region","city","lat","lon"])assert.equal(fallback[field],"");
assert.equal(fallback.module,"jkbms");
