"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const nodes = JSON.parse(fs.readFileSync(path.join(__dirname,"..","smart-jkbms-bluetooth","health_flows.json"),"utf8"));
const fn=nodes.find(n=>n.id==="b190021900000001");
const timer=nodes.find(n=>n.id==="b190021900000002");
const outDebug=nodes.find(n=>n.id==="b190021900000003");
assert(fn&&timer&&outDebug&&outDebug.active===true);
assert.equal(timer.repeat,"20");
const work=new Function("msg","context","node","Buffer","Date",fn.func);
const state=new Map();
const context={get:k=>state.get(k),set:(k,v)=>state.set(k,v)};
let now=100000;
const clock={now:()=>now};
const node={status:()=>{}};
const a="C8:47:80:1A:1A:EF",b="C8:47:80:1A:27:12";
function send(payload){return work({payload},context,node,Buffer,clock);}
for(const [mac,name,rssi] of [[a,"Batterie 1-01",-48],[b,"Batterie 2-02",-38]]){
 assert.equal(send({type:"device_found",address:mac,name,rssi}),null);
 assert.equal(send({type:"connected",address:mac}),null);
}
const broken=Buffer.alloc(300);
broken.set([0x55,0xaa,0xeb,0x90,2,30],0);
broken[299]=broken.subarray(0,299).reduce((acc,v)=>(acc+v)&255,0);
assert.equal(send({address:a,type:2,crc_ok:true,raw_hex:broken.toString("hex").toUpperCase(),sequence:30}),null);
const good=Buffer.alloc(300);
good.set([0x55,0xaa,0xeb,0x90,2,31]);
good.writeUInt32LE(0xffff,70);
for(let i=0;i<16;i++)good.writeUInt16LE(3200,6+2*i);
good.writeUInt32LE(51200,150);
good[173]=21;
good.writeInt16LE(166,162);
good.writeInt16LE(165,164);
good.writeInt16LE(185,144);
good[299]=good.subarray(0,299).reduce((acc,v)=>(acc+v)&255,0);
assert.equal(send({address:b,type:2,crc_ok:true,raw_hex:good.toString("hex").toUpperCase(),sequence:31}),null);
assert.equal(send({address:b,validation:"provisional_compare_with_BatMON",source_crc_ok:true,format:"JK02_32S",voltage_v:51.2,soc_pct:21}),null);
const results=send("health_tick");
assert(results&&Array.isArray(results[0]),"Node-RED function must return messages for one output");
assert.equal(results[0].length,2);
const aa=results[0].find(x=>x.topic.includes(a));
const bb=results[0].find(x=>x.topic.includes(b));
assert(aa.payload.includes("BLE connecté"),aa.payload);
assert(aa.payload.includes("TRAME REÇUE MAIS NON DÉCODÉE"),aa.payload);
assert(aa.payload.includes("24S:"),aa.payload);
assert(aa.payload.includes("32S:"),aa.payload);
assert(bb.payload.includes("décodage JK02_32S"),bb.payload);
assert(!bb.payload.includes("TRAME REÇUE MAIS NON DÉCODÉE"),bb.payload);
now+=3000;
assert.equal(send({address:a,type:"disconnected"}),null);
const again=send("health_tick");
assert(again[0].find(x=>x.topic.includes(a)).payload.includes("déconnecté"));
console.log("BMS health diagnostics tests pass: connected-but-undecoded, decoded peer, device disconnect, no event spam");
